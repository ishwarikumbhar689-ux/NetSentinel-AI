def load_synthetic(train_path, test_path):
    """Load pre-split synthetic CSVs produced by generate_dataset.py."""
    print(f"  Loading {train_path} …")
    train = pd.read_csv(train_path, low_memory=False)
    print(f"  Loading {test_path} …")
    test  = pd.read_csv(test_path,  low_memory=False)
    # Tag so main() can use the pre-split data directly
    train["_split"] = "train"
    test["_split"]  = "test"
    df = pd.concat([train, test], ignore_index=True)
    print(f"  Loaded {len(df):,} rows total  (train={len(train):,}  test={len(test):,})")
    return df


def load_unsw(train_path, test_path):
    """Load and combine UNSW-NB15 train/test splits."""
    print(f"  Loading {train_path} …")
    train = pd.read_csv(train_path, low_memory=False)
    print(f"  Loading {test_path} …")
    test  = pd.read_csv(test_path,  low_memory=False)
    df = pd.concat([train, test], ignore_index=True)
    print(f"  Loaded {len(df):,} rows total")
    return df


def load_cic(csv_path):
    """Load a CIC-IDS2017 CSV and strip leading/trailing spaces from column names."""
    print(f"  Loading {csv_path} …")
    df = pd.read_csv(csv_path, low_memory=False)
    df.columns = [c.strip() for c in df.columns]
    # Re-add the leading space that the config expects, OR you can
    # update the config to use stripped names — both work.
    # Here we just strip and update config keys to match stripped names:
    global DATASET_CONFIG
    cfg = DATASET_CONFIG["CIC_IDS2017"]
    cfg["features"]    = [c.strip() for c in cfg["features"]]
    cfg["numeric"]     = [c.strip() for c in cfg["numeric"]]
    cfg["categorical"] = [c.strip() for c in cfg["categorical"]]
    cfg["label_col"]   = cfg["label_col"].strip()
    cfg["app_to_model"] = {k: v.strip() for k, v in cfg["app_to_model"].items()}
    print(f"  Loaded {len(df):,} rows total")
    return df


def encode_label_cic(series):
    """Convert CIC labels: BENIGN → 0, anything else → 1."""
    return (series.str.strip().str.upper() != "BENIGN").astype(int)


def clean_data(df, cfg):
    """Drop rows with NaN/inf in feature columns and the label column."""
    cols = cfg["features"] + [cfg["label_col"]]
    before = len(df)
    df = df[cols].copy()
    df = df.replace([np.inf, -np.inf], np.nan)
    df = df.dropna()
    print(f"  Cleaned: kept {len(df):,} / {before:,} rows")
    return df


# ═══════════════════════════════════════════════════════════════
# MAIN TRAINING FLOW
# ═══════════════════════════════════════════════════════════════

def main():
    if DATASET not in DATASET_CONFIG:
        print(f"ERROR: DATASET must be 'SYNTHETIC', 'UNSW_NB15', or 'CIC_IDS2017', got '{DATASET}'")
        sys.exit(1)

    cfg = DATASET_CONFIG[DATASET]

    # ── 1. Load data ──────────────────────────────────────────
    print("\n[1/6] Loading dataset …")
    if DATASET == "SYNTHETIC":
        for f in [SYNTHETIC_TRAIN_CSV, SYNTHETIC_TEST_CSV]:
            if not os.path.exists(f):
                print(f"\nERROR: File not found: {f}")
                print("Run generate_dataset.py first:")
                print("  .\\venv\\Scripts\\python.exe generate_dataset.py")
                sys.exit(1)
        df = load_synthetic(SYNTHETIC_TRAIN_CSV, SYNTHETIC_TEST_CSV)
    elif DATASET == "UNSW_NB15":
        for f in [UNSW_TRAIN_CSV, UNSW_TEST_CSV]:
            if not os.path.exists(f):
                print(f"\nERROR: File not found: {f}")
                print("Download UNSW-NB15 from:")
                print("  https://research.unsw.edu.au/projects/unsw-nb15-dataset")
                sys.exit(1)
        df = load_unsw(UNSW_TRAIN_CSV, UNSW_TEST_CSV)
    else:
        if not os.path.exists(CIC_CSV):
            print(f"\nERROR: File not found: {CIC_CSV}")
            print("Download CIC-IDS2017 from:")
            print("  https://www.unb.ca/cic/datasets/ids-2017.html")
            sys.exit(1)
        df = load_cic(CIC_CSV)

    # ── 2. Prepare labels ─────────────────────────────────────
    print("\n[2/6] Preparing labels …")
    if DATASET == "CIC_IDS2017":
        df[cfg["label_col"]] = encode_label_cic(df[cfg["label_col"]])

    # For SYNTHETIC, clean only feature+label cols (drop the _split tag)
    if DATASET == "SYNTHETIC":
        df = clean_data(df, cfg)
    else:
        df = clean_data(df, cfg)

    y = df[cfg["label_col"]].astype(int)
    print(f"  Class distribution:\n    Normal (0): {(y==0).sum():,}  |  Attack (1): {(y==1).sum():,}")

    # ── 3. Encode categorical columns ─────────────────────────
    print("\n[3/6] Encoding categorical features …")
    X = df[cfg["features"]].copy()
    encoders = {}
    for col in cfg["categorical"]:
        le = LabelEncoder()
        X[col] = le.fit_transform(X[col].astype(str))
        encoders[col] = le
        print(f"  Encoded '{col}' -> {len(le.classes_)} categories")

    # ── 4. Split (BEFORE fitting scaler to prevent data leakage) ──
    print("\n[4/6] Splitting into train / test …")
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )
    print(f"  Train: {len(X_train):,} rows  |  Test: {len(X_test):,} rows")

    # ── 5. Build and train pipeline ───────────────────────────
    print(f"\n[5/6] Training Random Forest ({N_ESTIMATORS} trees) …")
    pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("model",  RandomForestClassifier(
            n_estimators=N_ESTIMATORS,
            random_state=42,
            n_jobs=-1,          # use all CPU cores
            class_weight="balanced",   # handles class imbalance
        ))
    ])
    pipeline.fit(X_train, y_train)
    print("  Training complete.")

    # ── 6. Evaluate ───────────────────────────────────────────
    print("\n[6/6] Evaluating …")
    y_pred = pipeline.predict(X_test)

    acc  = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred, zero_division=0)
    rec  = recall_score(y_test, y_pred, zero_division=0)
    f1   = f1_score(y_test, y_pred, zero_division=0)

    print(f"\n  Accuracy : {acc*100:.2f}%")
    print(f"  Precision: {prec*100:.2f}%")
    print(f"  Recall   : {rec*100:.2f}%")
    print(f"  F1-Score : {f1*100:.2f}%")

    print("\n  Classification Report:")
    print(classification_report(
        y_test, y_pred,
        target_names=["Normal", "Potentially Suspicious"],
        zero_division=0
    ))

    print("  Confusion Matrix (rows=actual, cols=predicted):")
    cm = confusion_matrix(y_test, y_pred)
    print(f"    [TN={cm[0][0]:,}  FP={cm[0][1]:,}]")
    print(f"    [FN={cm[1][0]:,}  TP={cm[1][1]:,}]")

    # Feature importance
    rf = pipeline.named_steps["model"]
    importances = sorted(
        zip(cfg["features"], rf.feature_importances_),
        key=lambda x: x[1], reverse=True
    )
    print("\n  Top feature importances:")
    for feat, imp in importances[:6]:
        bar = "█" * int(imp * 40)
        print(f"    {feat:<30} {imp:.4f}  {bar}")

    # ── Save model bundle ─────────────────────────────────────
    bundle = {
        "pipeline":     pipeline,       # StandardScaler + RandomForest
        "features":     cfg["features"],
        "numeric":      cfg["numeric"],
        "categorical":  cfg["categorical"],
        "encoders":     encoders,       # fitted LabelEncoders per categorical column
        "app_to_model": cfg["app_to_model"],
        "dataset":      DATASET,
    }
    joblib.dump(bundle, MODEL_PATH)
    print(f"\n  Saved -> {MODEL_PATH}  ({os.path.getsize(MODEL_PATH)//1024} KB)")

    print("\n" + "="*60)
    print("  Model training complete!")
    print(f"  Restart app.py — it will load '{MODEL_PATH}' automatically.")
    print("="*60 + "\n")


if __name__ == "__main__":
    main()
